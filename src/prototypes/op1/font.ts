// Letters with accents fall back to their plain letter; anything else is a box.
const FALLBACK = '##### #...# #...# #...# #...# #...# #####';
const plain = (c) => c.normalize('NFD').replace(/[̀-ͯ]/g, '');

const rows = new Map<string, string[]>(Object.entries(GLYPHS).map(([c, g]) => [c, g ? g.split(" ") : []]));

function glyphRows(c) {
  return rows.get(c) ?? rows.get(plain(c)) ?? FALLBACK.split(' ');
}

/** The pixels lit for [text], as [x, y] pairs from its top left. */
export function textPixels(text) {
  const out = [];
  [...text].forEach((c, i) => {
    glyphRows(c).forEach((row, y) => {
      for (let x = 0; x < GLYPH_W; x++) if (row[x] === '#') out.push([i * ADVANCE + x, y]);
    });
  });
  return out;
}

export const textWidth = (text) => Math.max(0, [...text].length * ADVANCE - 1);
